test('late WebOTP from an aborted phone context cannot fill or submit for the next identity',async()=>{
 let oldDone,newDone;
 const get=jest.fn().mockImplementationOnce(()=>new Promise(r=>oldDone=r)).mockImplementationOnce(()=>new Promise(r=>newDone=r));
 Object.defineProperty(window,'OTPCredential',{configurable:true,value:function(){}});
 Object.defineProperty(navigator,'credentials',{configurable:true,value:{get}});
 loginApi.verifyOtp.mockResolvedValue({status:200,data:{token:'synthetic',role:'Staff'}});
 const view=render(<Harness phoneNumber="0501111111"/>);
 expect(get).toHaveBeenCalledTimes(1);
 view.rerender(<Harness phoneNumber="0502222222"/>);
 expect(get.mock.calls[0][0].signal.aborted).toBe(true);
 expect(get).toHaveBeenCalledTimes(2);
 await act(async()=>oldDone({code:'654321'}));
 expect(screen.getByLabelText('otp').value).toBe('');
 expect(loginApi.verifyOtp).not.toHaveBeenCalled();
 await act(async()=>newDone({code:'123456'}));
 await waitFor(()=>expect(mockNavigate).toHaveBeenCalled());
 expect(loginApi.verifyOtp).toHaveBeenCalledTimes(1);
 expect(loginApi.verifyOtp).toHaveBeenCalledWith({phoneNumber:'0502222222',tenantSlug:undefined},'123456');
 delete window.OTPCredential;
});
